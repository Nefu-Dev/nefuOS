// GF(2^8) 乘 2（xtime）
static unsigned char xtime(unsigned char b) {
    return (unsigned char)((b << 1) ^ ((b & 0x80) ? 0x1b : 0));
}

// 轮常量
static const unsigned char RCON[11] = { 0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36 };

// 密钥扩展：16 字节 → 11 轮密钥（176 字节）
static void expand_key(const unsigned char key[16], unsigned char rk[176]) {
    for (int i = 0; i < 16; i++) rk[i] = key[i];
    for (int i = 4; i < 44; i++) {
        unsigned char t[4];
        for (int j = 0; j < 4; j++) t[j] = rk[(i - 1) * 4 + j];
        if (i % 4 == 0) {
            // RotWord + SubWord + Rcon
            unsigned char tmp = t[0];
            t[0] = SBOX[t[1]]; t[1] = SBOX[t[2]]; t[2] = SBOX[t[3]]; t[3] = SBOX[tmp];
            t[0] ^= RCON[i / 4];
        }
        for (int j = 0; j < 4; j++) rk[i * 4 + j] = rk[(i - 4) * 4 + j] ^ t[j];
    }
}

// 状态矩阵操作（以 4x4 字节按列存储）
static void add_round_key(unsigned char s[16], const unsigned char* rk, int round) {
    for (int i = 0; i < 16; i++) s[i] ^= rk[round * 16 + i];
}
static void sub_bytes(unsigned char s[16]) {
    for (int i = 0; i < 16; i++) s[i] = SBOX[s[i]];
}
static void inv_sub_bytes(unsigned char s[16]) {
    for (int i = 0; i < 16; i++) s[i] = RSBOX[s[i]];
}
// 行移位：行 r 左移 r 字节（状态按列存：s[r + 4*c]）
static void shift_rows(unsigned char s[16]) {
    unsigned char t[16];
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++) t[r + 4 * c] = s[r + 4 * ((c + r) % 4)];
    memcpy(s, t, 16);
}
static void inv_shift_rows(unsigned char s[16]) {
    unsigned char t[16];
    for (int r = 0; r < 4; r++)
        for (int c = 0; c < 4; c++) t[r + 4 * ((c + r) % 4)] = s[r + 4 * c];
    memcpy(s, t, 16);
}
// 列混合：每列乘矩阵 [2 3 1 1; 1 2 3 1; 1 1 2 3; 3 1 1 2]
static void mix_columns(unsigned char s[16]) {
    for (int c = 0; c < 4; c++) {
        unsigned char a0 = s[4*c], a1 = s[4*c+1], a2 = s[4*c+2], a3 = s[4*c+3];
        s[4*c]   = xtime(a0) ^ (a1 ^ xtime(a1)) ^ a2 ^ a3;
        s[4*c+1] = a0 ^ xtime(a1) ^ (a2 ^ xtime(a2)) ^ a3;
        s[4*c+2] = a0 ^ a1 ^ xtime(a2) ^ (a3 ^ xtime(a3));
        s[4*c+3] = (a0 ^ xtime(a0)) ^ a1 ^ a2 ^ xtime(a3);
    }
}
static void inv_mix_columns(unsigned char s[16]) {
    // 逆矩阵乘 [14 11 13 9; 9 14 11 13; 13 9 14 11; 11 13 9 14]
    for (int c = 0; c < 4; c++) {
        unsigned char a0 = s[4*c], a1 = s[4*c+1], a2 = s[4*c+2], a3 = s[4*c+3];
        // 用 xtime 组合乘 2/4/8
        unsigned char b0 = a0, b1 = a1, b2 = a2, b3 = a3;
        unsigned char x2_0 = xtime(a0), x2_1 = xtime(a1), x2_2 = xtime(a2), x2_3 = xtime(a3);
        unsigned char x4_0 = xtime(x2_0), x4_1 = xtime(x2_1), x4_2 = xtime(x2_2), x4_3 = xtime(x2_3);
        unsigned char x8_0 = xtime(x4_0), x8_1 = xtime(x4_1), x8_2 = xtime(x4_2), x8_3 = xtime(x4_3);
        s[4*c]   = x8_0 ^ x4_0 ^ x2_0 ^ x8_1 ^ x2_1 ^ b1 ^ x8_2 ^ x4_2 ^ b2 ^ x8_3 ^ b3;
        s[4*c+1] = x8_0 ^ b0 ^ x8_1 ^ x4_1 ^ x2_1 ^ x8_2 ^ x2_2 ^ b2 ^ x8_3 ^ x4_3 ^ b3;
        s[4*c+2] = x8_0 ^ x4_0 ^ b0 ^ x8_1 ^ b1 ^ x8_2 ^ x4_2 ^ x2_2 ^ x8_3 ^ x2_3 ^ b3;
        s[4*c+3] = x8_0 ^ x2_0 ^ b0 ^ x8_1 ^ x4_1 ^ b1 ^ x8_2 ^ b2 ^ x8_3 ^ x4_3 ^ x2_3;
    }
}

void aes128_encrypt_block(const unsigned char key[16],
                          const unsigned char in[16], unsigned char out[16]) {
    unsigned char rk[176];
    expand_key(key, rk);
    unsigned char s[16];
    memcpy(s, in, 16);
    add_round_key(s, rk, 0);
    for (int round = 1; round <= 9; round++) {
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, rk, round);
    }
    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, rk, 10);
    memcpy(out, s, 16);
}

void aes128_decrypt_block(const unsigned char key[16],
                          const unsigned char in[16], unsigned char out[16]) {
    unsigned char rk[176];
    expand_key(key, rk);
    unsigned char s[16];
    memcpy(s, in, 16);
    add_round_key(s, rk, 10);
    // 逆最后一轮（加密第 10 轮 = Sub → Shift → AddKey）
    inv_shift_rows(s);
    inv_sub_bytes(s);
    for (int round = 9; round >= 1; round--) {
        // 逆序撤销加密轮：AddKey → InvMixColumns → InvShiftRows → InvSubBytes
        add_round_key(s, rk, round);
        inv_mix_columns(s);
        inv_shift_rows(s);
        inv_sub_bytes(s);
    }
    add_round_key(s, rk, 0);
    memcpy(out, s, 16);
}

void aes128_encrypt(const unsigned char key[16],
                    const unsigned char* in, int n, unsigned char* out) {
    for (int i = 0; i + 16 <= n; i += 16)
        aes128_encrypt_block(key, in + i, out + i);
}

void aes128_decrypt(const unsigned char key[16],
                    const unsigned char* in, int n, unsigned char* out) {
    for (int i = 0; i + 16 <= n; i += 16)
        aes128_decrypt_block(key, in + i, out + i);
}

// ---- self test ----
namespace {
int g_fails = 0;
void expect(const char* what, bool ok) { if (!ok) { g_fails++; printf("FAIL: %s\n", what); } (void)what; }
} // namespace

int aes_self_test() {
    g_fails = 0;
    // FIPS-197 附录 B 测试向量：密钥 000102...0f，明文 001122...ff
    {
        unsigned char key[16], pt[16], ct[16], rt[16];
        for (int i = 0; i < 16; i++) { key[i] = (unsigned char)i; pt[i] = (unsigned char)(i * 0x11); }
        static const unsigned char expect_ct[16] = {
            0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a
        };
        aes128_encrypt_block(key, pt, ct);
        bool ok = memcmp(ct, expect_ct, 16) == 0;
        expect("aes-fips-ct", ok);
        aes128_decrypt_block(key, ct, rt);
        expect("aes-fips-roundtrip", memcmp(rt, pt, 16) == 0);
    }
    // 往返测试：多块
    {
        unsigned char key[16], data[64], enc[64], dec[64];
        for (int i = 0; i < 16; i++) key[i] = (unsigned char)(i * 7 + 3);
        for (int i = 0; i < 64; i++) data[i] = (unsigned char)(i * 13 + 1);
        aes128_encrypt(key, data, 64, enc);
        aes128_decrypt(key, enc, 64, dec);
        expect("aes-multiblock", memcmp(dec, data, 64) == 0);
    }
    // 雪崩：改 1 位明文，密文大不同
    {
        unsigned char key[16], pt1[16], pt2[16], ct1[16], ct2[16];
        for (int i = 0; i < 16; i++) key[i] = (unsigned char)(i + 5);
        for (int i = 0; i < 16; i++) { pt1[i] = (unsigned char)(i * 3); pt2[i] = pt1[i]; }
        pt2[0] ^= 1;
        aes128_encrypt_block(key, pt1, ct1);
        aes128_encrypt_block(key, pt2, ct2);
        int diff = 0;
        for (int i = 0; i < 16; i++) for (int b = 0; b < 8; b++) if (((ct1[i] ^ ct2[i]) >> b) & 1) diff++;
        expect("aes-avalanche", diff >= 40);
    }
    return g_fails;
}

