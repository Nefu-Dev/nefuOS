// nefuOS 压缩算法库 —— 游程编码（RLE）模块
//
// 本模块实现四类最基础的"消除重复"编码器，全部教学友好、逐字节可逆：
//
//   1. PackBits（Apple Macintosh 位图 / TIFF 经典格式）
//      用一个有符号控制字节区分"字面量串"与"重复字节串"，
//      是理解 RLE 如何在"重复"和"扩张"之间取舍的最佳范例。
//
//   2. 字节 RLE（转义符版）
//      用一个转义字节标记"接下来是 计数+重复字节"，
//      对连续相同字节（如图像行、单色画面）非常有效。
//
//   3. 零值压缩（Zero RLE）
//      专门针对"大量 0 字节"的稀疏数据（内存转储、位图、矩阵），
//      用标记 + 长度把一长串 0 折叠成两三个字节。
//
//   4. 比特 RLE（bit-RLE）
//      按比特而非按字节计游程，适合二值图像（1-bit 位图、压缩后残余比特流）。
//
// 所有接口统一约定：
//   encode  : 输入 in[in_len]，输出到 out[out_cap]，返回写入字节数；
//             若缓冲区不足返回 -1。
//   decode  : 输入 in[in_len]，还原到 out[out_cap]，返回还原字节数；
//             失败返回 -1。
//   每个函数都必须满足 round-trip：decode(encode(x)) == x 逐字节相等。
#pragma once
#include <stdint.h>
#include <stddef.h>

namespace nefu {
namespace compress {

// -----------------------------------------------------------------
// 1) PackBits
//    控制字节 c 按有符号解释：
//      c >= 0  -> 后面跟 c+1 个字面量字节（共 1..128 个）
//      c <  0  -> 后面跟 1 个字节，重复 -(c+1) 次（共 2..128 次）
//    最坏情况下不可压缩数据会略微膨胀（每 128 字节多 1 字节头）。
// -----------------------------------------------------------------
int packbits_encode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);
int packbits_decode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);

// -----------------------------------------------------------------
// 2) 通用字节 RLE（转义符版）
//    转义字节固定为 0xFB。遇到长度 >= 3 的相同字节串时输出：
//        0xFB, <len>, <byte>
//    其余原样输出；若数据本身出现 0xFB，则输出 0xFB,0 表示"一个字面 0xFB"。
//    解码时读到 0xFB：若下一字节为 0 则还原一个 0xFB，否则重复该计数次。
// -----------------------------------------------------------------
int rle_byte_encode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);
int rle_byte_decode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);

// -----------------------------------------------------------------
// 3) 零值压缩
//    标记字节 0x9E。连续 >= 2 个 0 折叠为：
//        0x9E, <len_lo>, <len_hi>     （长度按 uint16 小端）
//    标记字节本身在数据里出现时输出 0x9E,0x00,0x00。
//    其余 0/非 0 字节原样输出。
// -----------------------------------------------------------------
int zero_encode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);
int zero_decode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);

// -----------------------------------------------------------------
// 4) 比特 RLE
//    先把整段数据按位展开成 0/1 序列（总共 in_len*8 位），
//    然后对连续相同的位计游程。
//    输出格式：
//        [u32 小端:总比特数] [u8:首个比特值] 然后一连串 u16 小端游程长度。
//    单个游程最长 65535，更长自动拆成多段（相邻段同值，解码自然拼接）。
// -----------------------------------------------------------------
int bitrle_encode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);
int bitrle_decode(const uint8_t* in, int in_len, uint8_t* out, int out_cap);

// -----------------------------------------------------------------
// 汇总自测：对全零 / 全相同 / 随机 / 英文文本 / 二进制混合等数据
// 做 round-trip，并验证可压缩数据的压缩比。
// 返回失败次数（0 表示全部通过）。
// -----------------------------------------------------------------
int rle_self_test();

} // namespace compress
} // namespace nefu
