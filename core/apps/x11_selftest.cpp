// core/apps/x11_selftest.cpp
//
// Boot-time check of the nefuOS embedded X11 server + guest socket mapping on
// the bare-metal backend.  A minimal static Linux ELF (a hand-built Xlib-style
// wire-protocol client) is baked into the VFS, loaded through the same
// parse -> build_guest -> execute chain as `deb run`, and talks to the X
// server: socket -> connect -> setup handshake -> CreateWindow/CreateGC/
// MapWindow -> Expose event -> PolyFillRectangle/PolyLine/ImageText8/PutImage.
// The kernel then inspects xs_fb pixels and the request/draw counters.
//
// NEFU_BARE only: the host backend has no CPU to run x86 ELF.
