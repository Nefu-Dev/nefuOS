static inline uint8_t xb_inb(uint16_t port){ uint8_t v; __asm__ volatile("inb %1, %0" : "=a"(v) : "Nd"(port)); return v; }
static inline void xb_outb(uint16_t port, uint8_t v){ __asm__ volatile("outb %0, %1" : : "a"(v), "Nd"(port)); }
static inline void xb_putc(char c) {
    while (!(xb_inb(0x3F8 + 5) & 0x20)) {}
    xb_outb(0x3F8, (uint8_t)c);
}
static void xb_puts(const char* s) { while (*s) xb_putc(*s++); }

static void xb_puthex(uint64_t v) {
    static const char hx[] = "0123456789abcdef";
    char b[20]; int n = 0;
    if (!v) { xb_putc('0'); return; }
    while (v) { b[n++] = hx[v & 15]; v >>= 4; }
    while (n) xb_putc(b[--n]);
}

// Linux write() on fd 1/2 -> UART.
static int xb_write(const void* buf, int64_t n, void* ud) {
    (void)ud;
    const char* p = (const char*)buf;
    for (int64_t i = 0; i < n; i++) xb_putc(p[i]);
    return (int)n;
}

// Seed /usr/share/apps/x11-hello.elf in the VFS (baked bytes).  Always
// overwrite: a stale file of the same length from a previous boot carries the
// old ELF layout and would be parsed instead of the freshly baked one.
static FSNode* ensure_x11_elf() {
    const char* path = "/usr/share/apps/x11-hello.elf";
    FSNode* f = g_vfs->resolve(path);
    if (!f || f->is_dir) {
        g_vfs->mkdir("/usr/share");
        g_vfs->mkdir("/usr/share/apps");
        f = g_vfs->create_file(path);
    }
    if (!f) return 0;
    if (!g_vfs->write_file(f, NEFU_X11_SELFCHECK_BIN, NEFU_X11_SELFCHECK_LEN)) return 0;
    return f;
}

extern "C" void nefu_x11_selftest(void) {
    xb_puts("\r\n[XREQ] nefuOS embedded X11 server selftest begin\r\n");
    xs_init();
    xs_dirty_reset();

    FSNode* f = ensure_x11_elf();
    if (!f) { xb_puts("[XREQ] bake FAIL (VFS)\r\n"); return; }
    xb_puts("[XREQ] baked client ELF size="); xb_puthex((uint64_t)f->size); xb_puts("\r\n");

    elf::Image img; memset(&img, 0, sizeof(img));
    if (elf::parse(f->data, f->size, img) != elf::E_OK) {
        xb_puts("[XREQ] elf parse FAIL\r\n"); return;
    }
    elf::Guest g; memset(&g, 0, sizeof(g));
    if (elf::build_guest(img, "/usr/share/apps/x11-hello.elf", g) != 0) {
        xb_puts("[XREQ] build_guest FAIL\r\n"); return;
    }
    elf::SysCtx ctx; memset(&ctx, 0, sizeof(ctx));
    ctx.x_fd = -1;                  // socket() syscall will open the X connection
    ctx.trace = 1;                  // print every guest syscall to COM1
    // Hard cap on guest syscalls: a hung client (e.g. stuck in a read loop
    // while the event queue is empty) must be forced out instead of spinning
    // forever and flooding the COM1 serial log.
    ctx.syscall_budget = 50000;
    ctx.write_fn = xb_write;
    ctx.brk_cur = g.brk; ctx.brk_limit = g.brk_limit;
    ctx.mmap_cur = g.brk; ctx.mmap_limit = g.brk_limit;

    // dump the 16 bytes the guest will execute at its entry point
    {
        const uint8_t* ep = (const uint8_t*)(uintptr_t)g.entry;
        xb_puts("[XREQ] entry bytes: ");
        static const char* hx = "0123456789abcdef";
        for (int i = 0; i < 16; i++) { xb_putc(hx[ep[i] >> 4]); xb_putc(hx[ep[i] & 15]); xb_putc(' '); }
        xb_puts("\r\n");
    }

    xb_puts("[XREQ] run guest X client\r\n");
    elf::execute(g, ctx);
    xb_puts("\r\n[XREQ] guest exited\r\n");

    xb_puts("[XREQ] req_count="); xb_puthex(xs_req_count);
    xb_puts(" draw_ops="); xb_puthex(xs_draw_ops);
    xb_puts(" windows="); xb_puthex((uint32_t)(int32_t)xs_window_count);
    xb_puts(" connected="); xb_puts(xs_connected() ? "1" : "0");
    xb_puts("\r\n");

    // Pixel evidence: window @(100,50) 500x400; fill rect @(20,20) 200x150.
    // Screen: rect spans (120,70)-(320,220) -> (130,80) must be white 0xFFFFFF.
    // Window bg (black, no bg attribute) -> (105,55) must be 0x000000.
    uint32_t p1 = xs_fb[80 * XS_W + 130];
    uint32_t p2 = xs_fb[55 * XS_W + 105];
    xb_puts("[XREQ] pixel rect="); xb_puthex(p1);
    xb_puts(" bg="); xb_puthex(p2);
    xb_puts("\r\n");

    int ok = (p1 == 0xFFFFFFu && p2 == 0x000000u);
    if (xs_req_count >= 7 && xs_draw_ops >= 4 && ok) {
        xb_puts("[XREQ] SELFTEST PASS\r\n");
    } else {
        xb_puts("[XREQ] SELFTEST FAIL\r\n");
    }

    // ---- Electron-style renderer window ----
    // Launch the same baked X client ELF through electron_launch_deb(), which
    // creates a WM window, runs the guest renderer against the embedded X
    // server, then paints the letterboxed framebuffer into the window surface.
    // PASS = a window was created and its back surface carries renderer pixels.
    {
        int wbefore = g_wm ? g_wm->windows().size() : 0;
        electron::electron_launch_deb("/usr/share/apps/x11-hello.elf");
        int wafter = g_wm ? g_wm->windows().size() : 0;
        Window* ew = (wafter > wbefore) ? g_wm->windows()[wafter - 1] : 0;
        uint32_t ewin_px = 0;
        if (ew) {
            if (ew->on_paint) ew->on_paint(ew);
            Surface& es = ew->back;
            for (int y = 0; y < es.height && !ewin_px; y += 3)
                for (int x = 0; x < es.width && !ewin_px; x += 3)
                    if (es.getpx(x, y) != 0) ewin_px = es.getpx(x, y);
        }
        xb_puts("[XREQ] electron wins="); xb_puthex((uint32_t)wafter);
        xb_puts(" px="); xb_puthex(ewin_px);
        xb_puts("\r\n");
        xb_puts(ewin_px ? "[XREQ] ELECTRON PASS\r\n" : "[XREQ] ELECTRON FAIL\r\n");
    }
    if (g.mem) kfree(g.mem);
}

