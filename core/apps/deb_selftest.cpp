// core/apps/deb_selftest.cpp
//
// Boot-time check of the nefuOS .deb environment on the bare-metal backend.
// If a real Debian .deb (ar archive) file is present in the VFS (e.g. dropped
// under /usr/share/apps by the host-side injector), this parses it, installs
// data.tar(.gz) into the VFS and runs the first static ELF through the same
// parse -> build_guest -> execute chain the terminal `deb run` uses.
// Output goes to COM1 so a headless QEMU run can be verified with `-serial file:`.
//
// NEFU_BARE only: the host backend has no CPU to run x86 ELF.
#include "../apps/apps.h"      // nefud_deb_probe / install / find_elf
#include "../elf/elfrun.h"     // parse -> build_guest -> execute
#include "../vfs/vfs.h"        // g_vfs / FSNode
#include "../klib/klib.h"
#include "../platform.h"
#include "deb_selfcheck_bin.h" // baked real .deb (ar + gzip tarballs + ELF)
#include <stdint.h>
#include <stddef.h>

#ifdef NEFU_BARE

namespace nefu {
namespace deb {

static inline uint8_t db_inb(uint16_t port){ uint8_t v; __asm__ volatile("inb %1, %0" : "=a"(v) : "Nd"(port)); return v; }
static inline void db_outb(uint16_t port, uint8_t v){ __asm__ volatile("outb %0, %1" : : "a"(v), "Nd"(port)); }
static inline void db_putc(char c) {
    while (!(db_inb(0x3F8 + 5) & 0x20)) {}
    db_outb(0x3F8, (uint8_t)c);
}
static void db_puts(const char* s) { while (*s) db_putc(*s++); }

static void db_puthex(uint64_t v) {
    static const char hx[] = "0123456789abcdef";
    char b[20]; int n = 0;
    if (!v) { db_putc('0'); return; }
    while (v) { b[n++] = hx[v & 15]; v >>= 4; }
    while (n) db_putc(b[--n]);
}

// Linux write() on fd 1/2 -> UART (the same sink the GUI `deb run` uses).
static int db_write(const void* buf, int64_t n, void* ud) {
    (void)ud;
    const char* p = (const char*)buf;
    for (int64_t i = 0; i < n; i++) db_putc(p[i]);
    return (int)n;
}

// Seed /usr/share/apps/hello.deb in the VFS if it is not already there
// (simulating a host-side drop of a real .deb into the system, or a `--vfsfile`
// injection).  Uses the baked bytes generated by tools/mk_deb_env.py.
static FSNode* ensure_hello_deb() {
    const char* path = "/usr/share/apps/hello.deb";
    FSNode* f = g_vfs->resolve(path);
    if (f && !f->is_dir && f->size == NEFU_DEB_SELFCHECK_LEN) return f;
    if (!f || f->is_dir) {
        g_vfs->mkdir("/usr/share");
        g_vfs->mkdir("/usr/share/apps");
        f = g_vfs->create_file(path);
    }
    if (!f) return 0;
    db_puts("[DEBREQ] bake: writing NEFU_DEB_SELFCHECK_LEN=");
    db_puthex((uint64_t)NEFU_DEB_SELFCHECK_LEN);
    db_puts(" bytes to ");
    db_puts(path);
    db_puts("\r\n");
    if (!g_vfs->write_file(f, NEFU_DEB_SELFCHECK_BIN, NEFU_DEB_SELFCHECK_LEN)) return 0;
    db_puts("[DEBREQ] bake: after write size=");
    db_puthex((uint64_t)f->size);
    db_puts(" head=");
    for (int i = 0; i < 8; i++) db_puthex((uint64_t)f->data[i]);
    db_puts("\r\n");
    return f;
}

// First file whose name ends in ".deb" inside `dir`.
static FSNode* find_first_deb(const char* dir) {
    FSNode* d = g_vfs->resolve(dir);
    if (!d || !d->is_dir) return 0;
    for (int i = 0; i < d->children.size(); i++) {
        FSNode* c = d->children[i];
        if (c->is_dir) continue;
        int n = c->name.len();
        if (n >= 4 && strcmp(c->name.c_str() + n - 4, ".deb") == 0) return c;
    }
    return 0;
}

// Print a NUL-terminated buffer verbatim (already formatted with \n).
static void db_print_buf(const char* b) { if (b) db_puts(b); }

extern "C" void nefu_deb_selftest(void) {
    db_puts("\r\n[DEBREQ] nefuOS .deb environment selftest begin\r\n");
    ensure_hello_deb();   // bake the demo .deb if nothing is there yet
    FSNode* f = find_first_deb("/usr/share/apps");
    if (!f) {
        db_puts("[DEBREQ] no .deb file found under /usr/share/apps (inject one)\r\n");
        return;
    }
    db_puts("[DEBREQ] package: /usr/share/apps/");
    db_puts(f->name.c_str());
    db_puts(" ("); db_puthex(f->size); db_puts(" B)\r\n");

    // 1) probe: member list + control fields
    {
        char buf[1024];
        if (nefud_deb_probe(f, buf, (int)sizeof(buf)) == 0) {
            db_puts("[DEBREQ] probe ok:\r\n");
            db_print_buf(buf);
        } else {
            db_puts("[DEBREQ] probe FAIL: "); db_print_buf(buf); db_puts("\r\n");
            return;
        }
    }

    // 2) install: unpack data.tar(.gz) into the VFS
    {
        char buf[512];
        int n = nefud_deb_install(f, buf, (int)sizeof(buf));
        db_puts("[DEBREQ] install -> ");
        db_print_buf(buf);
        db_puts(" (count="); db_puthex((uint64_t)(int64_t)n); db_puts(")\r\n");
        if (n < 0) return;
        char vp[300];
        if (!nefud_deb_find_elf(f, vp, (int)sizeof(vp))) {
            db_puts("[DEBREQ] no static ELF in data.tar; install-only package\r\n");
            return;
        }
        db_puts("[DEBREQ] elf path: "); db_puts(vp); db_puts("\r\n");
        FSNode* ef = g_vfs->resolve(vp);
        if (!ef || ef->is_dir || ef->size == 0) {
            db_puts("[DEBREQ] installed ELF not found in VFS\r\n");
            return;
        }

        // 3) run: same chain as `deb run` / runelf
        elf::Image img; memset(&img, 0, sizeof(img));
        int e = elf::parse(ef->data, ef->size, img);
        if (e != elf::E_OK) {
            db_puts("[DEBREQ] elf parse FAIL rc="); db_puthex((uint64_t)(int64_t)e); db_puts("\r\n");
            return;
        }
        elf::Guest g; memset(&g, 0, sizeof(g));
        int be = elf::build_guest(img, vp, g);
        if (be != 0) {
            db_puts("[DEBREQ] build_guest FAIL rc="); db_puthex((uint64_t)(int64_t)be); db_puts("\r\n");
            return;
        }
        elf::SysCtx ctx; memset(&ctx, 0, sizeof(ctx));
        ctx.x_fd = -1;                   // no X connection for the demo ELF
        ctx.write_fn = db_write;
        ctx.brk_cur = g.brk; ctx.brk_limit = g.brk_limit;
        ctx.mmap_cur = g.brk; ctx.mmap_limit = g.brk_limit;
        db_puts("[DEBREQ] run entry=0x"); db_puthex(g.entry);
        db_puts(" base=0x"); db_puthex(g.base); db_puts("\r\n");
        db_puts("[DEBREQ] program output:\r\n");
        // Jumps into the guest; its write() syscall lands on the UART.
        elf::execute(g, ctx);
        db_puts("\r\n[DEBREQ] run done\r\n");
        if (g.mem) kfree(g.mem);
    }
}

} // namespace deb
} // namespace nefu
#endif // NEFU_BARE
