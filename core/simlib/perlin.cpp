PerlinNoise::PerlinNoise(unsigned seed) {
    // 用线性同余构造置换表
    unsigned rng = seed ? seed : 1;
    unsigned char perm[256];
    for (int i = 0; i < 256; i++) perm[i] = (unsigned char)i;
    for (int i = 255; i > 0; i--) {
        rng = rng * 1664525 + 1013904223;
        int j = (int)(rng % (unsigned)(i + 1));
        unsigned char t = perm[i]; perm[i] = perm[j]; perm[j] = t;
    }
    for (int i = 0; i < 512; i++) p[i] = perm[i & 255];
}

int PerlinNoise::grad_noise(int ix, int iy) const {
    return p[(p[ix & 255] + iy) & 255];
}

double PerlinNoise::noise(double x, double y) const {
    int ix = (int)std::floor(x);
    int iy = (int)std::floor(y);
    double fx = x - ix, fy = y - iy;
    // 四个晶格梯度
    const double* g00 = GRAD[grad_noise(ix, iy) & 255];
    const double* g10 = GRAD[grad_noise(ix + 1, iy) & 255];
    const double* g01 = GRAD[grad_noise(ix, iy + 1) & 255];
    const double* g11 = GRAD[grad_noise(ix + 1, iy + 1) & 255];
    double n00 = g00[0] * fx + g00[1] * fy;
    double n10 = g10[0] * (fx - 1) + g10[1] * fy;
    double n01 = g01[0] * fx + g01[1] * (fy - 1);
    double n11 = g11[0] * (fx - 1) + g11[1] * (fy - 1);
    double u = fade(fx), v = fade(fy);
    double nx0 = lerp(n00, n10, u);
    double nx1 = lerp(n01, n11, u);
    double n = lerp(nx0, nx1, v);
    // 归一化到 [0,1]
    return n * 0.5 + 0.5;
}

double PerlinNoise::fractal(double x, double y, int octaves, double persistence) const {
    double total = 0, amp = 1, freq = 1, maxv = 0;
    for (int o = 0; o < octaves; o++) {
        total += noise(x * freq, y * freq) * amp;
        maxv += amp;
        amp *= persistence;
        freq *= 2;
    }
    if (maxv == 0) return 0;
    return total / maxv;
}

std::vector<double> PerlinNoise::height_map(int w, int h, int octaves, double persistence) const {
    std::vector<double> m(w * h);
    for (int y = 0; y < h; y++)
        for (int x = 0; x < w; x++)
            m[y * w + x] = fractal(x * 0.08, y * 0.08, octaves, persistence);
    return m;
}

std::string PerlinNoise::map_to_text(const std::vector<double>& m, int w, int h) {
    std::string s;
    for (int y = 0; y < h; y++) {
        for (int x = 0; x < w; x++) {
            double v = m[y * w + x];
            char c;
            if (v < 0.2) c = '.';
            else if (v < 0.4) c = ':';
            else if (v < 0.6) c = '*';
            else if (v < 0.8) c = 'o';
            else c = '@';
            s.push_back(c);
        }
        if (y + 1 < h) s.push_back('\n');
    }
    return s;
}

// ---- self test ----
int PerlinNoise::self_test() {
    int fails = 0;
    // 1. 范围测试：噪声值恒在 [0,1]
    {
        PerlinNoise pn(42);
        bool in_range = true;
        for (int i = 0; i < 2000; i++) {
            double v = pn.noise((double)(i % 97), (double)(i % 89));
            if (v < 0 || v > 1) in_range = false;
        }
        if (!in_range) fails++;
    }
    // 2. 确定性：同种子同输入同输出
    {
        PerlinNoise a(7), b(7);
        if (a.noise(3.3, 4.4) != b.noise(3.3, 4.4)) fails++;
        PerlinNoise c(99);
        if (c.noise(3.3, 4.4) == a.noise(3.3, 4.4)) fails++;   // 不同种子一般不同
    }
    // 3. 平滑性：相近输入输出差小
    {
        PerlinNoise pn(5);
        double v1 = pn.noise(10.0, 10.0);
        double v2 = pn.noise(10.001, 10.0);
        if (std::abs(v1 - v2) > 0.02) fails++;
    }
    // 4. 分形在 [0,1]
    {
        PerlinNoise pn(1);
        double f = pn.fractal(2.5, 3.5, 4, 0.5);
        if (f < 0 || f > 1) fails++;
    }
    // 5. 高度图与字符画
    {
        PerlinNoise pn(123);
        std::vector<double> m = pn.height_map(16, 12, 3, 0.5);
        if ((int)m.size() != 16 * 12) fails++;
        std::string t = PerlinNoise::map_to_text(m, 16, 12);
        if ((int)t.size() < 16 * 12) fails++;
        if (t.find('.') == std::string::npos && t.find(':') == std::string::npos &&
            t.find('*') == std::string::npos) fails++;   // 至少包含一种地形字符
    }
    return fails;
}

