#!/usr/bin/env python3
# nefuOS: generate tests/minijvm_cases.h from javac-compiled .class files.
#
# Reads every *.class under tests/java/out, embeds the bytes as C arrays and
# pairs each with the expected interpreter output (from the .expect files next
# to the .java sources). The headless minijvm test includes this header.
#
# Usage: python tools/gen_java_embed.py
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "tests", "java", "out")
HDR = os.path.join(ROOT, "tests", "minijvm_cases.h")

def c_arr(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    row = []
    for i, b in enumerate(data):
        row.append("0x%02X," % b)
        if len(row) == 16:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return "\n".join(lines)

def main():
    if not os.path.isdir(OUT_DIR):
        print("error: %s missing - run javac first" % OUT_DIR)
        return 1
    cases = []
    arrays = []
    for cls in sorted(glob.glob(os.path.join(OUT_DIR, "*.class"))):
        base = os.path.splitext(os.path.basename(cls))[0]
        if "$" in base:
            continue   # inner classes have no main; the outer class drives them
        with open(cls, "rb") as f:
            data = f.read()
        arr_name = "%s_class" % base
        arrays.append(c_arr(arr_name, data))
        expect_path = os.path.join(ROOT, "tests", "java", "%s.expect" % base)
        expect = ""
        if os.path.isfile(expect_path):
            with open(expect_path, "r", encoding="utf-8") as f:
                expect = f.read()
        esc = expect.replace("\r\n", "\n").replace("\r", "\n").replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        cases.append('    {"%s", %s, (unsigned int)sizeof(%s), "%s"}' %
                     (base, arr_name, arr_name, esc))
    if not cases:
        print("error: no .class files found under %s" % OUT_DIR)
        return 1
    with open(HDR, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/gen_java_embed.py - do not edit.\n")
        f.write("// Embeds javac-compiled .class fixtures for the minijvm headless test.\n")
        f.write("#pragma once\n\n")
        f.write("struct JavaCase {\n")
        f.write("    const char* name;\n")
        f.write("    const unsigned char* data;\n")
        f.write("    unsigned int size;\n")
        f.write("    const char* expect;\n")
        f.write("};\n\n")
        f.write("\n".join(arrays))
        f.write("\n\nstatic const JavaCase k_java_cases[] = {\n")
        f.write(",\n".join(cases))
        f.write("\n};\n")
        f.write("static const int k_java_case_count = %d;\n" % len(cases))
    print("wrote %s (%d cases)" % (HDR, len(cases)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
