# -*- coding: utf-8 -*-
"""
Generate the bare-metal demo video used by nefuOS.

The bare build has no host codec, so it ships a real (if small) video inside the
kernel image: an "NVID" container made of QOI-compressed frames, decoded at
runtime by core/apps/qoi_decode.h + the player's own frame scheduler.

Frames are extracted from lvgl's birds.mp4 with OpenCV, scaled down, and each
frame is QOI encoded (lossless, ~1 byte/pixel for photos, decode is a few dozen
lines of C++).
"""
import struct, sys
import cv2
import numpy as np

SRC = r"D:\mycppos1\nefuOS\third_party\lvgl_src\lvgl-9.2.0\examples\libs\ffmpeg\birds.mp4"
OUT_H = r"D:\mycppos1\nefuOS\core\apps\nvid_demo.h"

import os
W, H = int(os.environ.get('NVID_W', 160)), int(os.environ.get('NVID_H', 90))
FPS = int(os.environ.get('NVID_FPS', 12))
MAX_FRAMES = int(os.environ.get('NVID_FRAMES', 30))
START_SEC = 0.6      # skip the fade-in


def qoi_encode(rgba: bytes, w: int, h: int) -> bytes:
    """Minimal QOI encoder (RGBA, no colour-space hint)."""
    px = np.frombuffer(rgba, dtype=np.uint8).reshape(h, w, 4).astype(np.int32)
    out = bytearray(b"qoif")
    out += struct.pack(">II", w, h)   # QOI header is big-endian
    out += bytes([4, 0])                      # 4 channels, sRGB
    index = [np.zeros(4, dtype=np.int32) for _ in range(64)]
    prev = np.array([0, 0, 0, 255], dtype=np.int32)
    run = 0
    px_list = px.reshape(-1, 4)
    n = len(px_list)
    i = 0
    while i < n:
        c = px_list[i]
        if np.array_equal(c, prev):
            run += 1
            if run == 62 or i == n - 1:
                out.append(0xC0 | (run - 1))
                run = 0
            i += 1
            continue
        if run:
            out.append(0xC0 | (run - 1))
            run = 0
        idx = (c[0] * 3 + c[1] * 5 + c[2] * 7 + c[3] * 11) % 64
        if np.array_equal(index[idx], c):
            out.append(0x00 | idx)
        else:
            index[idx] = c
            dr = int(c[0] - prev[0]); dg = int(c[1] - prev[1])
            db = int(c[2] - prev[2]); da = int(c[3] - prev[3])
            # DIFF / LUMA never carry alpha, so they need da == 0
            if da == 0 and -2 <= dr <= 1 and -2 <= dg <= 1 and -2 <= db <= 1:
                out.append(0x40 | ((dr + 2) << 4) | ((dg + 2) << 2) | (db + 2))
            else:
                dr_dg = dr - dg
                db_dg = db - dg
                if da == 0 and -8 <= dr_dg <= 7 and -32 <= dg <= 31 and -8 <= db_dg <= 7:
                    out.append(0x80 | (dg + 32))
                    out.append(((dr_dg + 8) << 4) | (db_dg + 8))
                else:
                    # QOI_OP_RGB takes three bytes only; alpha stays at the
                    # previous value (frames are opaque, so 255)
                    out.append(0xFE)
                    out += struct.pack("<BBB", int(c[0]), int(c[1]), int(c[2]))
        prev = c.copy()
        i += 1
    out += b"\x00\x00\x00\x00\x00\x00\x00\x01"
    return bytes(out)


def main() -> int:
    cap = cv2.VideoCapture(SRC)
    if not cap.isOpened():
        print("cannot open", SRC)
        return 1
    fps = cap.get(cv2.CAP_PROP_FPS) or 25.0
    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)
    print("src: %.2f fps, %d frames" % (fps, total))
    start = int(START_SEC * fps)
    step = max(1, int(round(fps / FPS)))

    frames = []
    i = start
    while len(frames) < MAX_FRAMES and i < (total or 10**9):
        cap.set(cv2.CAP_PROP_POS_FRAMES, i)
        ok, bgr = cap.read()
        if not ok:
            break
        bgr = cv2.resize(bgr, (W, H), interpolation=cv2.INTER_AREA)
        rgba = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGBA)
        frames.append(qoi_encode(rgba.tobytes(), W, H))
        i += step
    cap.release()
    if not frames:
        print("no frames decoded")
        return 1

    blob = bytearray()
    blob += b"NVID"
    blob += struct.pack("<HHHH", W, H, FPS, len(frames))
    for f in frames:
        blob += struct.pack("<I", len(f))
        blob += f

    lines = []
    lines.append("/*")
    lines.append(" * nefuOS Copyright (C) 2026 nefu-dev")
    lines.append(" * Licensed under GNU GPLv2 <https://www.gnu.org/licenses/gpl-2.0.html>")
    lines.append(" * See COPYING for full license text.")
    lines.append(" */")
    lines.append("// GENERATED by tools/gen_nvid_demo.py - do not edit by hand.")
    lines.append("//")
    lines.append("// Built-in bare-metal demo video: NVID container, %d frames of %dx%d at %d fps,"
                 % (len(frames), W, H, FPS))
    lines.append("// each frame QOI compressed from lvgl's birds.mp4 (decoded by qoi_decode.h).")
    lines.append("#pragma once")
    lines.append("")
    lines.append("namespace nefu {")
    lines.append("static const unsigned char g_nvid_demo[] = {")
    hexs = ["0x%02X" % b for b in blob]
    for k in range(0, len(hexs), 16):
        lines.append("    " + ", ".join(hexs[k:k + 16]) + ",")
    lines.append("};")
    lines.append("static const unsigned int g_nvid_demo_size = %d;" % len(blob))
    lines.append("} // namespace nefu")
    lines.append("")
    with open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    raw = len(frames) * W * H * 4
    print("frames=%d container=%d B (raw would be %d B, %.1fx)"
          % (len(frames), len(blob), raw, raw / float(len(blob))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
