#!/usr/bin/env python3
# mk_deb_env.py - build the nefuOS .deb environment test assets.
#
# It produces a REAL Debian .deb (ar archive with gzip-compressed control and
# data tarballs) whose usr/bin contains the tiny static Linux ELF from
# mk_static_elf.py ("Hello from Linux ELF in nefuOS!").  The same .deb is:
#   1) emitted as a file (tools/samples/deb/real-elf.deb) so a user can drop it
#      into nefuOS (file manager double-click -> nefud viewer -> Install, or
#      terminal `deb install/run`), and
#   2) emitted as a C header (core/apps/deb_selfcheck_bin.h) that the bare
#      boot selftest bakes into /usr/share/apps/hello.deb for headless QEMU
#      verification of the whole parse -> install -> runelf chain.
#
# Also writes build/samples/deb_test.img: an ATA-disk image (LBA0 reserved,
# LBA1 = image size, LBA2.. = data) wrapping the current nefuos.fs NVFS, which
# is what the bare QEMU harness boots with -hda.
import io, os, sys, struct, tarfile, gzip

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PY = sys.executable

def build_elf(path):
    sub = os.path.join(HERE, "mk_static_elf.py")
    os.system('"%s" "%s" "%s"' % (PY, sub, path))
    with open(path, "rb") as f:
        return f.read()

def make_control_tar_gz():
    ctl = (
        "Package: nefu-hello\n"
        "Version: 1.0.0\n"
        "Section: utils\n"
        "Priority: optional\n"
        "Architecture: all\n"
        "Maintainer: nefuOS <dev@nefuos.invalid>\n"
        "Description: nefuOS .deb environment demo package\n"
        " A real Debian .deb containing a static Linux ELF that\n"
        " nefuOS can parse, install and run headlessly.\n"
    ).encode()
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz", format=tarfile.GNU_FORMAT) as t:
        ti = tarfile.TarInfo("DEBIAN/control")
        ti.size = len(ctl)
        ti.mode = 0o644
        t.addfile(ti, io.BytesIO(ctl))
    return buf.getvalue()

def make_data_tar_gz(elf, readme):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz", format=tarfile.GNU_FORMAT) as t:
        ti = tarfile.TarInfo("usr/bin/hello")
        ti.size = len(elf)
        ti.mode = 0o755
        t.addfile(ti, io.BytesIO(elf))
        di = tarfile.TarInfo("usr/share/doc/nefu-hello/")
        di.type = tarfile.DIRTYPE
        di.mode = 0o755
        t.addfile(di)
        ri = tarfile.TarInfo("usr/share/doc/nefu-hello/readme.txt")
        ri.size = len(readme)
        ri.mode = 0o644
        t.addfile(ri, io.BytesIO(readme))
    return buf.getvalue()

def ar_hdr(name, size):
    # 60-byte ar member header: name(16) date(12) uid(6) gid(6) mode(8) size(10) magic(2)
    n = name if isinstance(name, bytes) else name.encode()
    assert len(n) <= 16
    return (n.ljust(16, b" ") + b"0".ljust(12, b" ") + b"0".ljust(6, b" ") +
            b"0".ljust(6, b" ") + b"100644".ljust(8, b" ") +
            str(size).encode().ljust(10, b" ") + b"`\n")

def make_deb(control_tgz, data_tgz):
    out = b"!<arch>\n"
    for name, payload in [(b"debian-binary", b"2.0\n"),
                          (b"control.tar.gz", control_tgz),
                          (b"data.tar.gz", data_tgz)]:
        out += ar_hdr(name, len(payload)) + payload
        if len(payload) % 2:
            out += b"\n"
    return out

def c_header(data, name="NEFU_DEB_SELFCHECK_BIN", lenname="NEFU_DEB_SELFCHECK_LEN"):
    lines = ["// Generated by tools/mk_deb_env.py - do not edit by hand.",
             "// A real Debian .deb (ar + control.tar.gz + data.tar.gz) carrying a",
             "// static Linux ELF at usr/bin/hello, for the boot .deb selftest.",
             "static const uint8_t %s[] = {" % name]
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i+20]) + ",")
    lines.append("};")
    lines.append("static const unsigned %s = %d;" % (lenname, len(data)))
    return "\n".join(lines) + "\n"

def main():
    elf_path = os.path.join(ROOT, "build", "samples", "hello-linux-elf")
    os.makedirs(os.path.dirname(elf_path), exist_ok=True)
    elf = build_elf(elf_path)
    readme = b"nefu-hello: nefuOS .deb environment demo.\n"
    ctl_tgz = make_control_tar_gz()
    data_tgz = make_data_tar_gz(elf, readme)
    deb = make_deb(ctl_tgz, data_tgz)

    out_deb = os.path.join(HERE, "samples", "deb", "real-elf.deb")
    with open(out_deb, "wb") as f:
        f.write(deb)
    print("wrote %s (%d bytes)" % (out_deb, len(deb)))

    # sanity: parse it back like the kernel does (ar members -> gzip -> tar)
    assert deb[:8] == b"!<arch>\n"
    pos = 8
    members = {}
    while pos + 60 <= len(deb):
        hdr = deb[pos:pos + 60]
        nm = hdr[:16].rstrip().decode()
        size = int(hdr[48:58].decode().strip() or 0)
        members[nm] = deb[pos + 60: pos + 60 + size]
        pos += 60 + size + (size % 2)
    assert set(members) == {"debian-binary", "control.tar.gz", "data.tar.gz"}
    assert gzip.decompress(members["control.tar.gz"])
    data = gzip.decompress(members["data.tar.gz"])
    assert data.find(b"\x7fELF") > 0
    print("sanity: ar members OK, data.tar.gz inflates, ELF present")

    hdr_path = os.path.join(ROOT, "core", "apps", "deb_selfcheck_bin.h")
    with open(hdr_path, "w") as f:
        f.write(c_header(deb))
    print("wrote %s (%d bytes of C array)" % (hdr_path, len(deb)))

    # ATA-disk image wrapping the current nefuos.fs (LBA0 reserved, LBA1 = size,
    # LBA2.. = NVFS image) for the bare QEMU harness.
    fs_path = os.path.join(ROOT, "nefuos.fs")
    if os.path.exists(fs_path):
        with open(fs_path, "rb") as f:
            img = f.read()
        sz = len(img)
        out = bytearray(b"\x00" * 512)
        out += struct.pack("<I", sz) + b"\x00" * 508
        out += img
        out += b"\x00" * (512 - (len(out) % 512))
        disk = os.path.join(ROOT, "build", "samples", "deb_test.img")
        with open(disk, "wb") as f:
            f.write(bytes(out))
        print("wrote %s (%d bytes, nvfs=%d)" % (disk, len(out), sz))

if __name__ == "__main__":
    main()
